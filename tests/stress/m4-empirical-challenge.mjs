// Component Loader using Astro's Rust compiler & runtime container
const componentCache = new Map();

async function loadAstroComponent(filename) {
  if (componentCache.has(filename)) {
    return componentCache.get(filename);
  }

  const filePath = path.join(COMP_DIR, filename);
  const src = fs.readFileSync(filePath, 'utf8');
  const compiled = transform(src, { filename });

  // In Astro 5/7 runtime, createMetadata is generated by compiler but handled at runtime.
  // We shim it safely so the compiled module loads identically to the Vite SSR pipeline.
  let code = compiled.code.replace(/,\s*createMetadata as \$\$createMetadata/g, '');
  code = 'const $$createMetadata = (name, meta) => ({ name, ...meta });\n' + code;

  const targetFile = path.join(CACHE_DIR, filename.replace('.astro', `.${Date.now()}.${Math.random().toString(36).slice(2)}.mjs`));
  fs.writeFileSync(targetFile, code);

  const mod = await import(pathToFileURL(targetFile).href);
  componentCache.set(filename, mod.default);
  return mod.default;
}

// Empirical Test Runner
class ChallengeRunner {
  constructor() {
    this.suites = [];
    this.currentSuite = null;
    this.totalAssertions = 0;
  }

  suite(name) {
    const s = { name, tests: [], passed: 0, failed: 0 };
    this.suites.push(s);
    this.currentSuite = s;
    return s;
  }

  async test(name, fn) {
    const t = { name, passed: false, assertions: 0, error: null, durationMs: 0 };
    this.currentSuite.tests.push(t);
    const start = performance.now();

    const customAssert = {
      ok: (val, msg) => {
        this.totalAssertions++;
        t.assertions++;
        assert.ok(val, msg);
      },
      strictEqual: (act, exp, msg) => {
        this.totalAssertions++;
        t.assertions++;
        assert.strictEqual(act, exp, msg);
      },
      notStrictEqual: (act, exp, msg) => {
        this.totalAssertions++;
        t.assertions++;
        assert.notStrictEqual(act, exp, msg);
      },
      deepStrictEqual: (act, exp, msg) => {
        this.totalAssertions++;
        t.assertions++;
        assert.deepStrictEqual(act, exp, msg);
      },
      match: (act, reg, msg) => {
        this.totalAssertions++;
        t.assertions++;
        assert.match(act, reg, msg);
      },
      doesNotMatch: (act, reg, msg) => {
        this.totalAssertions++;
        t.assertions++;
        assert.doesNotMatch(act, reg, msg);
      },
      greaterThan: (a, b, msg) => {
        this.totalAssertions++;
        t.assertions++;
        assert.ok(a > b, msg || `Expected ${a} > ${b}`);
      },
      lessThan: (a, b, msg) => {
        this.totalAssertions++;
        t.assertions++;
        assert.ok(a < b, msg || `Expected ${a} < ${b}`);
      },
      includes: (haystack, needle, msg) => {
        this.totalAssertions++;
        t.assertions++;
        assert.ok(haystack && haystack.includes(needle), msg || `Expected inclusion of "${needle}"`);
      },
      notIncludes: (haystack, needle, msg) => {
        this.totalAssertions++;
        t.assertions++;
        assert.ok(!haystack || !haystack.includes(needle), msg || `Expected exclusion of "${needle}"`);
      },
    };

    try {
      await fn(customAssert);
      t.passed = true;
      this.currentSuite.passed++;
    } catch (err) {
      t.passed = false;
      t.error = err;
      this.currentSuite.failed++;
    } finally {
      t.durationMs = performance.now() - start;
    }
  }
}

